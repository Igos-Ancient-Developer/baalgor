// клетки, по которым идёт дорога (внутри поля)
export function expand(path) {
  const cells = [];
  for (let i = 1; i < path.length; i++) {
    const [c0, r0] = path[i - 1], [c1, r1] = path[i];
    const dc = Math.sign(c1 - c0), dr = Math.sign(r1 - r0); let c = c0, r = r0;
    for (let first = true; ; first = false) { if (!(i > 1 && first) && c >= 0 && c < COLS && r >= 0 && r < ROWS) cells.push([c, r]); if (c === c1 && r === r1) break; c += dc; r += dr; }
  }
  return cells;
}
